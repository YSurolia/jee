// Lesson: The Solid State.
var R = String.raw;
JEE.lesson('chemistry', 'solid-state', {
  theory: [
    { h: R`Types of solids`,
      body: [R`<b>Crystalline</b> solids have long-range order, sharp melting points and are anisotropic. <b>Amorphous</b> solids (glass, rubber) have only short-range order, soften over a range and are isotropic.`, R`Crystalline solids are molecular, ionic, metallic or covalent network solids, depending on the particles and forces.`] },
    { h: R`Unit cells and crystal systems`,
      body: [R`The unit cell is the smallest repeating unit of a lattice, described by a, b, c and α, β, γ. There are 7 crystal systems and 14 Bravais lattices.`, R`Cubic cells: simple (1 atom), body-centred (2), face-centred (4). Corner = ⅛, edge = ¼, face = ½, body = 1.`] },
    { h: R`Close packing and efficiency`,
      body: [R`ABAB… stacking gives hcp; ABCABC… gives ccp (= fcc). Both have coordination number 12 and 74% packing. bcc: coordination 8, 68%. Simple cubic: 6, 52.4%.`, R`Radius relations: sc a = 2r; bcc √3a = 4r; fcc √2a = 4r.`],
      analogy: R`Stacking oranges at a fruit stall: each layer sits in the dips of the one below, which is the densest way to pile spheres.` },
    { h: R`Density of a unit cell`,
      body: [R`\(d = \dfrac{ZM}{a^3N_A}\). Use a in cm to get g/cm³ (1 pm = 10⁻¹⁰ cm).`] },
    { h: R`Voids and ionic structures`,
      body: [R`In close packing of N spheres: 2N tetrahedral and N octahedral voids.`, R`Radius ratio r₊/r₋: 0.225–0.414 → CN 4; 0.414–0.732 → CN 6; 0.732–1 → CN 8. NaCl (6:6), CsCl (8:8), ZnS (4:4), CaF₂ (8:4).`] },
    { h: R`Defects`,
      body: [R`Schottky: cation–anion pairs missing; density decreases (NaCl, KCl). Frenkel: smaller ion moves to an interstitial site; density unchanged (ZnS, AgCl). AgBr shows both.`, R`Impurity defects: Sr²⁺ in NaCl creates cation vacancies. F-centres (electrons in anion vacancies) colour crystals.`],
      mistake: R`Thinking a Frenkel defect lowers density. Nothing leaves the crystal, so the density is unchanged.` }
  ],

  examples: [
    { level: 1, t: 3, q: R`How many atoms are present in a body-centred cubic unit cell?`,
      steps: [R`8 corners × ⅛ = 1; 1 body centre.`], ans: R`2` },
    { level: 1, t: 0, q: R`Classify as molecular, ionic, metallic or covalent network: (a) diamond (b) dry ice (c) MgO (d) brass.`,
      steps: [R`Match the particles and forces.`], ans: R`(a) covalent network (b) molecular (c) ionic (d) metallic` },
    { level: 1, t: 2, q: R`What is the coordination number of an atom in (a) hcp (b) bcc?`,
      steps: [R`Close-packed structures have 12 neighbours; bcc has 8.`], ans: R`(a) 12 (b) 8` },
    { level: 2, t: 4, q: R`Atoms of B form a ccp lattice and A atoms occupy half the tetrahedral voids. Find the formula.`,
      steps: [R`N atoms of B give 2N tetrahedral voids; A = ½ × 2N = N.`], ans: R`AB` }
  ],

  practice: [
    { level: 1, type: 'mcq', q: R`Which is an amorphous solid?`,
      options: [R`quartz`, R`glass`, R`NaCl`, R`diamond`], correct: 1,
      solution: R`Glass has only short-range order.` },
    { level: 1, type: 'mcq', q: R`The number of atoms in a face-centred cubic unit cell is:`,
      options: [R`1`, R`2`, R`4`, R`6`], correct: 2,
      solution: R`8 × ⅛ + 6 × ½ = 4.` },
    { level: 1, type: 'mcq', q: R`The packing efficiency of a simple cubic lattice is about:`,
      options: [R`52%`, R`68%`, R`74%`, R`90%`], correct: 0,
      solution: R`π/6 ≈ 52.4%.` },
    { level: 1, type: 'mcq', q: R`In a Schottky defect, the density of the crystal:`,
      options: [R`increases`, R`stays the same`, R`decreases`, R`first increases then decreases`], correct: 2,
      solution: R`Ions are missing from the lattice.` },
    { level: 1, type: 'num', q: R`How many octahedral voids are there in a ccp array of 50 atoms?`,
      answer: 50, tol: 0, unit: '',
      solution: R`Octahedral voids = N = 50.` },
    { level: 1, type: 'num', q: R`A simple cubic metal has edge length 300 pm. Find its atomic radius (in pm).`,
      answer: 150, tol: 0.5, unit: 'pm',
      solution: R`a = 2r, so r = 150 pm.` },
    { level: 2, type: 'mcq', q: R`Which crystal system has a = b ≠ c and α = β = γ = 90°?`,
      options: [R`cubic`, R`tetragonal`, R`orthorhombic`, R`hexagonal`], correct: 1,
      solution: R`Tetragonal: two equal edges, all right angles.` },
    { level: 2, type: 'mcq', q: R`A compound has X at the corners and Y at the body centre of a cubic cell. Its formula is:`,
      options: [R`XY`, R`XY₂`, R`X₂Y`, R`XY₈`], correct: 0,
      solution: R`X: 8 × ⅛ = 1; Y: 1.` },
    { level: 2, type: 'mcq', q: R`Frenkel defects are common in:`,
      options: [R`NaCl`, R`KCl`, R`AgCl`, R`CsCl`], correct: 2,
      solution: R`Ag⁺ is much smaller than Cl⁻ and moves easily into interstitial sites.` },
    { level: 2, type: 'mcq', q: R`For a radius ratio of 0.52, the expected coordination number is:`,
      options: [R`3`, R`4`, R`6`, R`8`], correct: 2,
      solution: R`0.414–0.732 gives octahedral coordination (6).` },
    { level: 2, type: 'num', q: R`Copper is fcc with an atomic radius of 128 pm. Find its edge length (in pm).`,
      answer: 362.0, tol: 1, unit: 'pm',
      solution: R`\(a = 2\sqrt2\,r = 2.828\times128\approx362\) pm.` },
    { level: 2, type: 'num', q: R`Find the density (in g/cm³) of a bcc metal with M = 23 g/mol and a = 429 pm. (N_A = 6.022 × 10²³)`,
      answer: 0.969, tol: 0.01, unit: 'g/cm³',
      solution: R`\(d = \dfrac{2\times23}{(4.29\times10^{-8})^3\times6.022\times10^{23}}\approx0.97\) g/cm³ (sodium).` },
    { level: 2, type: 'num', q: R`In NaCl, r(Na⁺) = 95 pm and r(Cl⁻) = 181 pm. Find the edge length of the unit cell (in pm).`,
      answer: 552, tol: 1, unit: 'pm',
      solution: R`Ions touch along the edge: a = 2(95 + 181) = 552 pm.` },
    { level: 3, type: 'mcq', q: R`Oxide ions are in ccp; cation A occupies 1/8 of the tetrahedral voids and cation B half the octahedral voids. The formula is:`,
      options: [R`AB₂O₄`, R`A₂BO₄`, R`AB₄O₂`, R`ABO₃`], correct: 0,
      solution: R`Per N oxide ions: A = ⅛ × 2N = N/4, B = ½N. A : B : O = ¼ : ½ : 1 = 1 : 2 : 4 (a spinel).` },
    { level: 3, type: 'mcq', q: R`Heating KCl in potassium vapour turns it violet because of:`,
      options: [R`Frenkel defects`, R`F-centres`, R`interstitial K atoms`, R`Schottky defects`], correct: 1,
      solution: R`Electrons trapped in anion vacancies (F-centres) absorb visible light.` },
    { level: 3, type: 'num', q: R`An element has an fcc structure with a = 400 pm and density 10 g/cm³. Find its molar mass (in g/mol).`,
      answer: 96.35, tol: 0.5, unit: 'g/mol',
      solution: R`\(M = \dfrac{d\,a^3N_A}{Z} = \dfrac{10\times(4\times10^{-8})^3\times6.022\times10^{23}}{4}\approx96.4\) g/mol.` },
    { level: 3, type: 'num', q: R`What fraction (in %) of the volume of a bcc unit cell is empty?`,
      answer: 32, tol: 0.2, unit: '%',
      solution: R`Packing efficiency is 68%, so 32% is empty.` }
  ]
});
